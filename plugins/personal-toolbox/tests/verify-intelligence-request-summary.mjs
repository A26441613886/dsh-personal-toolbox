import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFile } from 'node:fs/promises';

const source = await readFile(new URL('../src/intelligence/client.js', import.meta.url), 'utf8');
const start = source.indexOf('function intelligenceRequestSummary(');
const end = source.indexOf('function IntelligenceRequestEvidence(', start);
assert.ok(start >= 0 && end > start);
const summarize = vm.runInNewContext(source.slice(start, end) + ';intelligenceRequestSummary');
const known = { completed: true, raw: '21', cacheEvidence: null, transport: { observed: true, attempts: 1, responses: 1, failures: 0, status: 200 } };
assert.equal(summarize({}).request.text, '未记录，暂时无法确认');
assert.match(summarize({}).next, /不等于没有发送/);
assert.equal(summarize({ raw: '21', requestId: 'local-id', upstreamResponseId: 'remote-id' }).request.tone, 'muted', 'IDs are not transport proof');
assert.equal(summarize({ raw: '21' }).duplicate.text, '这条记录缺少检查证据', 'Old records without checks must not be labelled fresh');
assert.equal(summarize({ ...known, transport: { observed: false, attempts: 1, responses: 1 } }).request.tone, 'muted');
assert.equal(summarize(known).request.text, '已发出，接口已响应');
assert.equal(summarize(known).duplicate.text, '未发现与已存记录重复');
assert.match(summarize(known).next, /是否重新生成，仍需/);
for (const cacheEvidence of ['same-body', 'same-id-and-body']) {
  const value = summarize({ ...known, cacheEvidence });
  assert.equal(value.duplicate.text, '完整回答与历史相同');
  assert.match(value.next, /不能单独证明用了缓存/);
}
assert.equal(summarize({ ...known, cacheEvidence: 'same-id' }).duplicate.text, '仅编号重复，回答内容不同');
assert.match(summarize({ ...known, cacheEvidence: 'same-id' }).next, /不能因为编号重复/);
assert.equal(summarize({ cacheWarning: 'legacy warning' }).duplicate.tone, 'warn');
assert.match(summarize({ pending: true }).request.text, /检测中/);
assert.match(summarize({ ...known, pending: true, cacheEvidence: 'same-body' }).duplicate.text, /尚未完成/);
const waiting = { observed: true, attempts: 1, responses: 0, failures: 0 };
assert.equal(summarize({ pending: true, transport: waiting }).request.text, '正在请求，等待接口响应');
assert.equal(summarize({ completed: false, transport: { ...waiting, failures: 1 } }).request.text, '已尝试请求，但未收到接口响应');
assert.match(summarize({ completed: false, transport: waiting }).next, /不能确认供应商是否收到/);
assert.match(summarize({ ...known, completed: false }).next, /本轮未完成/);
assert.equal(summarize({ ...known, transport: { ...known.transport, status: 429 } }).request.text, '接口返回错误（HTTP 429）');
assert.match(summarize({ ...known, transport: { ...known.transport, status: 500 } }).next, /不代表模型降智/);
assert.equal(summarize({ serverElapsedMs: 166340 }).duration, '2 分 46 秒');
assert.equal(summarize({ serverElapsedMs: 41080 }).duration, '41 秒');
assert.equal(summarize({ serverElapsedMs: 0 }).duration, '0 秒');
assert.equal(summarize({ serverElapsedMs: NaN }).duration, '');
assert.equal(summarize({ serverElapsedMs: -1 }).duration, '');
const retryWaiting = summarize({ pending: true, retrying: true, retryCount: 1, maxRetries: 3 });
assert.equal(retryWaiting.request.text, '等待自动重试 2/3');
assert.equal(retryWaiting.retry, '等待重试 2/3');
assert.match(retryWaiting.next, /可能再次计费/);
assert.equal(summarize({ pending: true, retryCount: 2 }).retry, '正在重试 2/3');
assert.equal(summarize({ ...known, retryCount: 3 }).retry, '已重试 3/3');
assert.equal(summarize(known).retry, '');
const original = JSON.stringify(known); summarize(known); assert.equal(JSON.stringify(known), original);
const component = source.slice(end, source.indexOf('function IntelligenceModelPicker(', end));
assert.match(component, /技术详情（排查时再看）/);
assert.doesNotMatch(component, /open:\s*true/);
assert.doesNotMatch(component, /fetch\(|\.run\(|localStorage|indexedDB/);
console.log('PASS: plain-language request summaries, unknown != unsent, response != regeneration, duplicates vs ID reuse, pending/failure/legacy cases, duration, read-only presentation and collapsed technical details.');
